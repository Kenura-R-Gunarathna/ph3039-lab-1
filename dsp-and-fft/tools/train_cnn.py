#!/usr/bin/env python3
"""Train the 1D-CNN keyword spotter and export it for apps/voice_cnn.

    pixi run train-cnn                  # pretrain on synthetic sentences, fine-tune on all real sessions, export
    pixi run train-cnn --cv             # also report held-out accuracy (5-fold, whole prompt texts held out)

1. Pretrain on synthetic continuous sentences (isolated words stitched together, exact word times known).
2. Fine-tune on the real continuous sessions in dataset_raw/. Word positions in those are not labelled: they are
   found by aligning the model's own window probabilities to the keywords of each prompt (in order).
3. Fold BatchNorm into the convolutions and write common/cnn_params.h for the firmware.
The reusable parts (data, Trainer, decoder) live in tools/kws.py; notebooks/sentence_cnn.ipynb walks through them.
"""
import argparse, os, sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kws import *

ap = argparse.ArgumentParser()
ap.add_argument("--steps", type=int, default=3500, help="pretraining steps")
ap.add_argument("--ft-steps", type=int, default=700, help="fine-tuning steps")
ap.add_argument("--retrain", action="store_true", help="ignore a saved pretrained model")
ap.add_argument("--cv", action="store_true", help="report held-out accuracy (5-fold by prompt text)")
ap.add_argument("--out", default="common/cnn_params.h")
ap.add_argument("--models", default="models")
ap.add_argument("--seed", type=int, default=0)
args = ap.parse_args()
torch.set_num_threads(4)
os.makedirs(args.models, exist_ok=True)
pre_path, norm_path = f"{args.models}/kws_pretrain.pt", f"{args.models}/kws_norm.npz"
reuse = os.path.exists(pre_path) and os.path.exists(norm_path) and not args.retrain

tr = Trainer(args.models, args.seed, fresh_norm=not reuse)
print("word pool:", {k: len(v) for k, v in tr.pool.words.items()}, "| background frames:", len(tr.pool.bg))
print(f"synthetic sentences: {len(tr.train)} | real sentences: {len(tr.real)} | window classes: "
      f"{ {CLASSES[c]: len(tr.byc[c]) for c in range(len(CLASSES))} }")
MU, SD = tr.MU, tr.SD

if reuse:
    net0 = KwsCnn(); net0.load_state_dict(torch.load(pre_path)); net0.eval()
    print("loaded", pre_path)
else:
    print("KwsCnn parameters:", sum(p.numel() for p in KwsCnn().parameters()))
    net0 = tr.pretrain(args.steps)
    torch.save(net0.state_dict(), pre_path)
    np.savez(norm_path, mu=MU, sd=SD)

if args.cv:
    res0, res1 = tr.cv_by_text(net0, 5, args.ft_steps)
    for name, r_ in [("synthetic only", res0), ("+ real sentences", res1)]:
        e, k = score(r_)
        print(f"held-out prompt texts, stride {STRIDE}, firmware decoder: {name:18s} exact {e:3.0f}%   keyword error {k:3.0f}%")

net, nwin = tr.finetune(net0, tr.real, args.ft_steps)
e, k = score([(stream_decode(probs(net, u["L"])), u["want"]) for u in tr.real])
print(f"final model fine-tuned on {len(tr.real)} real sentences ({nwin} windows); on those same sentences: exact {e:.0f}%  keyword error {k:.0f}%")
torch.save(net.state_dict(), f"{args.models}/kws_cnn.pt")


# ------------------------------------------------------------------ export: fold BatchNorm into the convolutions
def folded(conv, bn):
    s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    w = conv.weight * s.view(-1, 1, 1)
    b = (conv.bias - bn.running_mean) * s + bn.bias
    return w.detach().numpy().transpose(0, 2, 1), b.detach().numpy()      # (out, k, in)


m = net.net
layers = [folded(m[0], m[1]), folded(m[3], m[4]), folded(m[6], m[7]), folded(m[9], m[10])]
fcw, fcb = net.fc.weight.detach().numpy(), net.fc.bias.detach().numpy()


def arr(a):
    if a.ndim == 1:
        return "{" + ", ".join(f"{v:.9g}f" for v in a) + "}"
    return "{\n" + ",\n".join("  " + arr(x) for x in a) + "\n}"


dims = [(NM, 32), (32, 48), (48, 64), (64, 64)]
txt = ["// GENERATED by tools/train_cnn.py -- do not edit by hand.",
       f"// 1D CNN keyword spotter: classes {CLASSES}, window {W} frames x {NM} mel, BatchNorm folded into the convolutions.",
       "#pragma once", "", f"#define KWS_NCLASS {len(CLASSES)}",
       "static const char *const kKwsClasses[KWS_NCLASS] = {" + ", ".join(f'"{c}"' for c in CLASSES) + "};",
       "// log-mel normalisation: (dB - mean) / std per mel band",
       f"static const float kKwsMean[{NM}] = {arr(MU.astype(np.float32))};",
       f"static const float kKwsStd[{NM}] = {arr(SD.astype(np.float32))};", ""]
for n, ((wt, bi), (ci, co)) in enumerate(zip(layers, dims), 1):
    txt += [f"// conv{n}: {ci} -> {co} channels, kernel 3, weights [out][tap][in]",
            f"static const float kConv{n}W[{co}][3][{ci}] = {arr(wt)};",
            f"static const float kConv{n}B[{co}] = {arr(bi)};", ""]
txt += ["// classifier on [mean over time, max over time] of the last layer",
        f"static const float kFcW[KWS_NCLASS][{2 * 64}] = {arr(fcw)};",
        f"static const float kFcB[KWS_NCLASS] = {arr(fcb)};", ""]
os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
open(args.out, "w").write("\n".join(txt))
nparam = sum(w.size + b.size for w, b in layers) + fcw.size + fcb.size
print(f"wrote {args.out}: {nparam} floats ({nparam * 4 / 1024:.0f} KB of flash)")
