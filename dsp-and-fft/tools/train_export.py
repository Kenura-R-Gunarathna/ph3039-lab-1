#!/usr/bin/env python3
"""Train the deployment classifier on ALL clips and write it as a C header for apps/voice_dsp.

    pixi run train-export --classes noise off on   # default 7 features, C=1
    pixi run train-export --features zcr hipos b1 b3 peak_db crest b2 --C 1

Model = z-score scaling + multinomial logistic regression (what notebooks/train_classifier.ipynb chose).
Classes are whatever folders exist in dataset/ (alphabetical), so after recording new words
(e.g. green, blue) just run this again and rebuild the firmware.
"""
import argparse, datetime, os, sys

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold, RepeatedStratifiedKFold, cross_val_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import voice_features as vf

ap = argparse.ArgumentParser()
ap.add_argument("--features", nargs="+", default=vf.FEATURE_NAMES, help="default: all 29")
ap.add_argument("--classes", nargs="+", default=None, help="dataset folders to use (default: all)")
ap.add_argument("--C", type=float, default=1.0)
ap.add_argument("--data", default="dataset")
ap.add_argument("--live", default="dataset_live", help="windows recorded by tools/live_session.py (used if the folder exists)")
ap.add_argument("--out", default="apps/voice_dsp/model_params.h")
args = ap.parse_args()

ids = [vf.FEATURE_NAMES.index(n) for n in args.features]
X, y, paths = vf.load_dataset(args.data, classes=args.classes)   # board-style windows: train as you deploy
if os.path.isdir(args.live):                                       # + windows the board really captured (sentences, quick words)
    Xl, yl, pl = vf.load_dataset(args.live, classes=args.classes, mode="raw")
    if len(yl):
        print("live windows:", {str(c): int((yl == c).sum()) for c in sorted(set(yl))})
        X, y, paths = np.vstack([X, Xl]), np.concatenate([y, yl]), paths + pl
classes = sorted(str(c) for c in set(y))
counts = {str(c): int((y == c).sum()) for c in classes}
print("classes:", counts, "| features:", args.features, "| C =", args.C)

# groups of 10 consecutive recordings of one word: holding out whole groups avoids near-duplicate neighbours
seen = {}
groups = []
for p_, c_ in zip(paths, y):
    seen[c_] = seen.get(c_, -1) + 1
    groups.append(f"{c_}-{seen[c_] // 10}")
model = make_pipeline(StandardScaler(), LogisticRegression(C=args.C, max_iter=5000, class_weight="balanced"))
cv = RepeatedStratifiedKFold(n_splits=5, n_repeats=5, random_state=0)
cvs = cross_val_score(model, X[:, ids], y, cv=cv)
print(f"cross-validation accuracy (random clips):          {cvs.mean() * 100:.1f} +- {cvs.std() * 100:.1f} %")
blk = cross_val_score(model, X[:, ids], y, cv=GroupKFold(5), groups=groups)
print(f"cross-validation accuracy (held-out blocks of 10): {blk.mean() * 100:.1f} +- {blk.std() * 100:.1f} %   <- the one to trust")
model.fit(X[:, ids], y)
print(f"training accuracy: {model.score(X[:, ids], y) * 100:.1f} %")

sc, lr = model[0], model[1]
assert list(lr.classes_) == classes
f = lambda a: ", ".join(f"{v:.8g}f" for v in a)
rows = ",\n    ".join("{" + f(r) + "}" for r in lr.coef_)
text = f"""// GENERATED by tools/train_export.py on {datetime.date.today()} -- do not edit by hand.
// Model: z-score + logistic regression.  Clips per class: {counts}
// Cross-validation accuracy: {cvs.mean() * 100:.1f} % random clips, {blk.mean() * 100:.1f} % held-out blocks
#pragma once
#include <stdint.h>

#define MODEL_NUM_CLASSES  {len(classes)}
#define MODEL_NUM_FEATURES {len(ids)}

static const char *const kClassNames[MODEL_NUM_CLASSES] = {{{", ".join(f'"{c}"' for c in classes)}}};

// index into the 11 values from vfExtract(): {", ".join(vf.FEATURE_NAMES)}
static const uint8_t kFeatureIds[MODEL_NUM_FEATURES] = {{{", ".join(map(str, ids))}}};   // {" ".join(args.features)}

static const float kMean[MODEL_NUM_FEATURES] = {{{f(sc.mean_)}}};
static const float kStd[MODEL_NUM_FEATURES]  = {{{f(sc.scale_)}}};

static const float kWeights[MODEL_NUM_CLASSES][MODEL_NUM_FEATURES] = {{
    {rows}
}};
static const float kBias[MODEL_NUM_CLASSES] = {{{f(lr.intercept_)}}};
"""
os.makedirs(os.path.dirname(args.out), exist_ok=True)
open(args.out, "w").write(text)
print("wrote", args.out)
